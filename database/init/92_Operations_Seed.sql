-- 5.1 Insert missing ports from target list
INSERT INTO [Ports] ([Id], [Name], [Code], [IsActive])
SELECT t.[Id], t.[Name], t.[Code], 1
FROM #TargetPorts t
WHERE NOT EXISTS (SELECT 1 FROM [Ports] p WHERE p.[Code] = t.[Code]);

-- 5.2 Clean legacy ports not in target list and not referenced by any operations
DELETE FROM [Ports]
WHERE NOT EXISTS (SELECT 1 FROM #TargetPorts t WHERE t.[Code] = [Ports].[Code])
  AND NOT EXISTS (SELECT 1 FROM [ExportDetails] ed WHERE ed.[POLId] = [Ports].[Id] OR ed.[POWId] = [Ports].[Id] OR ed.[PODId] = [Ports].[Id])
  AND NOT EXISTS (SELECT 1 FROM [ImportDetails] id WHERE id.[PODId] = [Ports].[Id]);

-- 5.3 Deactivate any historical legacy ports that are referenced and could not be deleted
UPDATE [Ports]
SET [IsActive] = 0
WHERE NOT EXISTS (SELECT 1 FROM #TargetPorts t WHERE t.[Code] = [Ports].[Code])
  AND [IsActive] = 1;

DROP TABLE #TargetPorts;
